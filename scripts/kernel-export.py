#!/usr/bin/env python3
"""Export Image and prepared external-module build files from a completed build."""

import argparse
from contextlib import ExitStack
import fcntl
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import tarfile
import tempfile


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from kernel_state import support_files, verify_output
WRAPPER = b'''# Prepared output for external modules; generated by kernel-export.py.
kernel_output := $(abspath $(dir $(lastword $(MAKEFILE_LIST))))
export KBUILD_OUTPUT := $(kernel_output)
ifeq ($(strip $(M)$(KBUILD_EXTMOD)),)
$(error This output supports external modules only; supply M=/absolute/module/source)
endif
include $(kernel_output)/source/Makefile
'''


def sha256(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def export(build, kernel, archive):
    build, kernel, archive = (path.resolve() for path in (build, kernel, archive))
    if archive.exists():
        raise ValueError(f'Archive already exists: {archive}')
    if not (kernel / 'Makefile').is_file():
        raise ValueError(f'Kernel source not found: {kernel}')
    if Path(subprocess.check_output(['git', '-C', str(kernel), 'rev-parse', '--show-toplevel'], text=True).strip()).resolve() != kernel:
        raise ValueError('The kernel source must be its own Git checkout')
    commit = subprocess.check_output(['git', '-C', str(kernel), 'rev-parse', 'HEAD'], text=True).strip()
    if subprocess.check_output(['git', '-C', str(kernel), 'status', '--porcelain=v1'], text=True).strip():
        raise ValueError('Kernel source must match the clean source used by this build')
    with ExitStack() as stack:
        lock_path = build / '.kernel-build.lock'
        if lock_path.exists():
            lock = stack.enter_context(lock_path.open('rb'))
            try:
                fcntl.flock(lock, fcntl.LOCK_SH | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise ValueError('Kernel output is currently being built') from error
        report = json.loads((build / 'kernel-build.json').read_text())
        verified = verify_output(build) if (build / 'kernel-state.json').exists() else None
        if not isinstance(report, dict) or report.get('status') != 'built' or report.get('kernel_commit') != commit or report.get('arch') != 'arm64':
            raise ValueError('Expected a completed arm64 build of the supplied kernel source')
        for name, key in [('.config', 'config_sha256'), ('Module.symvers', 'symvers_sha256'),
                          ('arch/arm64/boot/Image', 'image_sha256')]:
            if sha256(build / name) != report.get(key):
                raise ValueError(f'File differs from completed build report: {name}')
        release = (build / 'include/config/kernel.release').read_text().strip()
        if release != report.get('kernelrelease'):
            raise ValueError('Kernel release differs from completed build report')
        config = set((build / '.config').read_text().splitlines())
        if 'CONFIG_MODULES=y' not in config:
            raise ValueError('The kernel does not enable modules')
        # These features need additional compiler artifacts beyond this export format.
        for symbol in ('CONFIG_RUST', 'CONFIG_DEBUG_INFO_BTF_MODULES', 'CONFIG_OBJTOOL'):
            if symbol + '=y' in config:
                raise ValueError(f'{symbol} requires additional build files; this export does not support it')

        payload = {'Image': build / 'arch/arm64/boot/Image', 'build/Makefile': WRAPPER}

        def add(relative):
            path = build / relative
            if not path.is_file() or path.is_symlink():
                raise ValueError(f'Required regular build file missing: {path}')
            payload['build/' + relative] = path

        for name in support_files(build):
            if name not in ('Makefile', 'arch/arm64/boot/Image'):
                add(name)

        files = {}
        for name, source in sorted(payload.items()):
            files[name] = ({'sha256': hashlib.sha256(source).hexdigest(), 'bytes': len(source), 'mode': 0o644}
                           if isinstance(source, bytes) else
                           {'sha256': sha256(source), 'bytes': source.stat().st_size,
                            'mode': source.stat().st_mode & 0o777})
        manifest = {'schema': 1, 'kind': 'w202ds-kernel-output', 'arch': 'arm64',
                    'host_system': platform.system(), 'host_machine': platform.machine(),
                    'kernel_commit': commit, 'kernelrelease': release,
                    'config_sha256': report['config_sha256'], 'symvers_sha256': report['symvers_sha256'],
                    'compiler': report.get('compiler'), 'profile': report.get('profile'), 'files': files}
        if verified:
            for key in ('source_identity', 'configuration'):
                manifest[key] = verified['state'][key]
        encoded = (json.dumps(manifest, indent=2) + '\n').encode()
        archive.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(prefix='.' + archive.name + '-', dir=archive.parent, delete=False) as temp:
            temporary = Path(temp.name)
        try:
            with temporary.open('wb') as raw, gzip.GzipFile(fileobj=raw, mode='wb', filename='', mtime=0) as compressed:
                with tarfile.open(fileobj=compressed, mode='w') as stream:
                    for name, source in [('manifest.json', encoded), *sorted(payload.items())]:
                        entry = tarfile.TarInfo(name)
                        entry.size = len(source) if isinstance(source, bytes) else files[name]['bytes']
                        entry.mode = 0o644 if name == 'manifest.json' else files[name]['mode']
                        if isinstance(source, bytes):
                            stream.addfile(entry, io.BytesIO(source))
                        else:
                            with source.open('rb') as data:
                                stream.addfile(entry, data)
            for name, source in payload.items():
                if isinstance(source, Path) and sha256(source) != files[name]['sha256']:
                    raise ValueError(f'Build changed during export: {source}')
            # A hard link publishes a complete archive and refuses to replace an existing file.
            os.link(temporary, archive)
        finally:
            temporary.unlink(missing_ok=True)
        return {'archive': str(archive), 'archive_sha256': sha256(archive), 'archive_bytes': archive.stat().st_size,
                'kernelrelease': release, 'image_bytes': files['Image']['bytes'],
                'module_build_bytes': sum(value['bytes'] for name, value in files.items() if name.startswith('build/')),
                'file_count': len(files)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, type=Path, help='completed kernel-build.py output directory')
    parser.add_argument('--kernel', type=Path, default=ROOT / 'kernel', help='matching clean kernel source')
    parser.add_argument('--archive', required=True, type=Path, help='new .tar.gz archive to create')
    args = parser.parse_args()
    try:
        print(json.dumps(export(args.out, args.kernel, args.archive), indent=2))
    except (OSError, ValueError, KeyError, subprocess.SubprocessError, tarfile.TarError) as error:
        parser.exit(1, f'kernel-export: {error}\n')


if __name__ == '__main__':
    main()
