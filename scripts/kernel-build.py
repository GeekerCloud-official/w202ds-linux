#!/usr/bin/env python3
"""Compose and build the W202DS kernel with Python 3.11+ and Linux Kbuild."""

import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shlex
import subprocess
import sys
import tempfile
import tomllib


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from kernel_state import configuration, current_configuration, file_records, source_identity
SETTING = re.compile(r'(CONFIG_[A-Za-z0-9_]+)=(y|m|n|-?[0-9]+|0[xX][0-9a-fA-F]+|"(?:[^"\\]|\\.)*")')
UNSET = re.compile(r'# (CONFIG_[A-Za-z0-9_]+) is not set')


class ConfigError(ValueError):
    pass


def digest(data):
    return hashlib.sha256(data).hexdigest()


def parse_config(data, path):
    """Retain locations and reject typos instead of silently dropping lines."""
    result = {}
    for number, raw in enumerate(data.decode().splitlines(), 1):
        line = raw.strip()
        assignment, unset = SETTING.fullmatch(line), UNSET.fullmatch(line)
        if assignment:
            name, value = assignment.groups()
        elif unset:
            name, value = unset[1], 'n'
        elif not line or line.startswith('#') and not line.startswith('# CONFIG_'):
            continue
        else:
            raise ConfigError(f'{path}:{number}: invalid configuration line: {line}')
        if name in result:
            raise ConfigError(f'{path}:{number}: duplicate setting {name}')
        result[name] = {'value': value, 'file': str(path), 'line': number}
    return result


def string_list(table, key, location):
    values = table.get(key, [])
    if not isinstance(values, list) or any(not isinstance(v, str) or not v for v in values):
        raise ConfigError(f'{location}: {key} must be a list of nonempty strings')
    return values


def compose(model_path, profile=None, fragments=()):
    model_path = Path(model_path).resolve()
    model_data = model_path.read_bytes()
    model = tomllib.loads(model_data.decode())
    if set(model) - {'schema', 'default', 'arch', 'profiles'} or type(model.get('schema')) is not int or model['schema'] != 1:
        raise ConfigError(f'{model_path}: unsupported model schema or keys')
    profiles = model.get('profiles')
    if not isinstance(profiles, dict) or not profiles:
        raise ConfigError(f'{model_path}: profiles must be a nonempty table')
    selected = profile or model.get('default')
    arch = model.get('arch')
    if not isinstance(arch, str) or not re.fullmatch(r'[A-Za-z0-9_]+', arch):
        raise ConfigError(f'{model_path}: invalid architecture')
    layers, inputs, settings, overrides = [], [], {}, []
    visited = set()

    def add_fragment(path, layer):
        path = Path(path).resolve()
        data = path.read_bytes()
        inputs.append({'path': str(path), 'sha256': digest(data), 'layer': layer})
        for name, setting in parse_config(data, path).items():
            setting['layer'] = layer
            if name in settings:
                overrides.append({'symbol': name, 'before': settings[name], 'after': setting})
            settings[name] = setting

    def visit(name, stack=()):
        if not isinstance(name, str) or name not in profiles:
            raise ConfigError(f'Unknown kernel profile: {name}')
        if name in stack:
            raise ConfigError('Profile inheritance cycle: ' + ' -> '.join((*stack, name)))
        if name in visited:
            return
        entry = profiles[name]
        if not isinstance(entry, dict) or set(entry) - {'extends', 'fragments', 'description'}:
            raise ConfigError(f'{model_path}: invalid profile {name}')
        for parent in string_list(entry, 'extends', name):
            visit(parent, (*stack, name))
        layers.append(name)
        for relative in string_list(entry, 'fragments', name):
            add_fragment(model_path.parent / relative, name)
        visited.add(name)

    visit(selected)
    for number, path in enumerate(fragments, 1):
        add_fragment(path, f'external-{number}')
    if not settings:
        raise ConfigError('The selected configuration contains no settings')
    return {'schema': 1, 'profile': selected, 'arch': arch,
            'model': {'path': str(model_path), 'sha256': digest(model_data)},
            'layers': layers, 'inputs': inputs, 'requested': settings, 'overrides': overrides}


def seed_config(settings):
    lines = ['# Generated by scripts/kernel-build.py; edit the input fragments.']
    for name, setting in settings.items():
        value = setting['value']
        lines.append(f'# {name} is not set' if value == 'n' else f'{name}={value}')
    return ('\n'.join(lines) + '\n').encode()


def unmet_settings(requested, final):
    result = []
    for name, source in requested.items():
        actual = final.get(name, {}).get('value', 'n')
        if actual != source['value']:
            result.append({'symbol': name, 'requested': source, 'actual': actual})
    return result


def write_atomic(path, data):
    """Each published file is complete, including after a failed generation."""
    with tempfile.NamedTemporaryFile(prefix='.' + path.name + '-', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(data)
            stream.flush()
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def clean_environment():
    env = {k: v for k, v in os.environ.items() if not k.startswith('KCONFIG_')}
    for name in ('KBUILD_OUTPUT', 'KBUILD_SRC', 'MAKEFLAGS', 'MFLAGS', 'MAKEOVERRIDES', 'LOCALVERSION'):
        env.pop(name, None)
    env.update(LC_ALL='C', LOCALVERSION='', GIT_OPTIONAL_LOCKS='0',
               KCONFIG_WARN_UNKNOWN_SYMBOLS='1', KCONFIG_WERROR='1')
    return env


def make(args, plan, directory, targets, log, capture=False):
    command = ['make', '--no-print-directory', '-s', '-C', str(args.kernel),
               'O=' + str(directory), 'ARCH=' + plan['arch'],
               'CROSS_COMPILE=' + args.cross_compile, 'LOCALVERSION=', 'KCONFIG_CONFIG=.config', *targets]
    log.write('$ ' + shlex.join(command) + '\n')
    log.flush()
    result = subprocess.run(command, env=clean_environment(), text=True,
                            stdout=subprocess.PIPE if capture else log, stderr=log)
    if capture:
        log.write(result.stdout)
        log.flush()
    if result.returncode:
        raise ConfigError(f'Kbuild failed with status {result.returncode}; inspect {log.name}')
    return result.stdout if capture else None


def generate(args, plan):
    args.kernel = args.kernel.resolve()
    out = args.out.resolve()
    inputs = [Path(plan['model']['path']), *(Path(item['path']) for item in plan['inputs'])]
    if out.is_relative_to(args.kernel) or any(p.is_relative_to(out) for p in inputs):
        raise ConfigError('Choose a build directory outside kernel/ that does not contain configuration inputs')
    if not (args.kernel / 'Makefile').is_file():
        raise ConfigError(f'Kernel source not found: {args.kernel}')
    identity = source_identity(args.kernel)
    out.mkdir(parents=True, exist_ok=True)
    with (out / '.kernel-build.lock').open('a') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as error:
            raise ConfigError(f'Another kernel task is using {out}') from error
        report = dict(plan, status='configuring', kernel=str(args.kernel), kernel_commit=identity['commit'],
                      source_identity=identity,
                      cross_compile=args.cross_compile, output=str(out))
        report_path = out / 'kernel-build.json'
        if report_path.exists():
            previous = json.loads(report_path.read_text())
            for key in ('kernel', 'arch', 'cross_compile'):
                if previous.get(key) != report[key]:
                    raise ConfigError(f'Build identity changed ({key}); choose a new output directory')
            if previous.get('kernel_commit') != identity['commit'] or previous.get('source_identity') != identity:
                raise ConfigError('Kernel source changed in a prepared build; choose a new output directory')
            if configuration(previous) != configuration(plan):
                raise ConfigError('Configuration inputs changed in a prepared build; choose a new output directory')
            if (out / '.config').exists() and previous.get('config_sha256') != digest((out / '.config').read_bytes()):
                raise ConfigError('Prepared configuration changed; choose a new output directory')

        def save():
            write_atomic(report_path, (json.dumps(report, indent=2, ensure_ascii=False) + '\n').encode())

        save()
        try:
            with tempfile.TemporaryDirectory(prefix='.configure-', dir=out) as temporary:
                candidate = Path(temporary)
                (candidate / '.config').write_bytes(seed_config(plan['requested']))
                with (out / 'configure.log').open('w') as log:
                    make(args, plan, candidate, ['olddefconfig'], log)
                    data = (candidate / '.config').read_bytes()
                    final = parse_config(data, candidate / '.config')
                    report['unmet'] = unmet_settings(plan['requested'], final)
                    if report['unmet']:
                        details = '; '.join(f"{e['symbol']} requested {e['requested']['value']} at "
                                            f"{e['requested']['file']}:{e['requested']['line']}, got {e['actual']}"
                                            for e in report['unmet'][:12])
                        raise ConfigError('Kconfig did not honor requested settings (check dependencies/choices): ' + details)
                    release = make(args, plan, candidate, ['kernelrelease'], log, capture=True).strip().splitlines()[-1]
                existing = out / '.config'
                if existing.exists() and any((out / n).exists() for n in ('vmlinux', 'Module.symvers', 'include/config/auto.conf')):
                    old = parse_config(existing.read_bytes(), existing)
                    if {k: v['value'] for k, v in old.items()} != {k: v['value'] for k, v in final.items()}:
                        raise ConfigError('Configuration changed in a prepared build; choose a new output directory')
                write_atomic(existing, data)
            report.update(status='configured', config_sha256=digest(data), kernelrelease=release,
                          option_counts={value: sum(e['value'] == value for e in final.values()) for value in ('y', 'm', 'n')},
                          compiler=final.get('CONFIG_CC_VERSION_TEXT', {}).get('value'))
            save()
            if args.action == 'build':
                report['status'] = 'building'
                save()
                with (out / 'build.log').open('w') as log:
                    make(args, plan, out, ['-j' + str(args.jobs), 'Image', 'modules'], log)
                built = parse_config((out / '.config').read_bytes(), out / '.config')
                if {k: v['value'] for k, v in built.items()} != {k: v['value'] for k, v in final.items()}:
                    raise ConfigError('Kbuild changed the verified configuration; inspect the build output')
                image, symbols = out / 'arch/arm64/boot/Image', out / 'Module.symvers'
                report.update(status='built', image_sha256=digest(image.read_bytes()),
                              symvers_sha256=digest(symbols.read_bytes()),
                              tree_module_count=sum(1 for _ in out.rglob('*.ko')))
                if source_identity(args.kernel) != identity:
                    raise ConfigError('Kernel source changed during the build')
                if current_configuration(configuration(plan)) != configuration(plan):
                    raise ConfigError('Configuration inputs changed during the build')
                state = {'schema': 1, 'kind': 'w202ds-kernel-output', 'arch': plan['arch'],
                         'host_system': platform.system(), 'host_machine': platform.machine(),
                         'kernel_commit': identity['commit'], 'source_identity': identity,
                         'kernelrelease': release, 'profile': plan['profile'],
                         'compiler': report['compiler'], 'configuration': configuration(plan),
                         'config_sha256': report['config_sha256'], 'symvers_sha256': report['symvers_sha256'],
                         'files': file_records(out)}
                write_atomic(out / 'kernel-state.json', (json.dumps(state, indent=2) + '\n').encode())
                save()
        except BaseException as error:
            report.update(status='failed', error=str(error))
            save()
            raise
    return {key: report[key] for key in ('status', 'profile', 'kernelrelease', 'config_sha256', 'output')}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('plan', 'configure', 'build'))
    parser.add_argument('--model', type=Path, default=ROOT / 'config/kernel/model.toml')
    parser.add_argument('--profile', help='default: the model default (debug)')
    parser.add_argument('--fragment', action='append', default=[], type=Path, help='external override; repeat in priority order')
    parser.add_argument('--kernel', type=Path, default=ROOT / 'kernel')
    parser.add_argument('--out', type=Path, required=True, help='independent Kbuild output directory')
    parser.add_argument('--cross-compile', default='aarch64-linux-gnu-')
    parser.add_argument('--jobs', type=int, default=4)
    args = parser.parse_args(argv)
    if args.jobs < 1:
        parser.error('--jobs must be positive')
    try:
        plan = compose(args.model, args.profile, args.fragment)
        result = dict(plan, output=str(args.out.resolve())) if args.action == 'plan' else generate(args, plan)
        print(json.dumps(result, indent=2, ensure_ascii=False))
    except (ConfigError, OSError, tomllib.TOMLDecodeError, subprocess.SubprocessError) as error:
        print(f'kernel-build: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
